<aside class="callout" role="note">
  <p class="callout-kicker">Set-out rule</p>
  <p class="callout-title">Put your trash can outside your door with the bagged trash inside it. Never put a loose bag on the ground.</p>
  <p>Tie the trash in a bag and put it inside your can. Set the can right outside your door during the set-out window, not on stairs or walkways. A second bag goes on top of the can, never on the ground or beside it. On extra-bag nights, extra bags go only on top of the can, never on the ground or beside it. Loose bags scatter garbage.</p>
</aside>
